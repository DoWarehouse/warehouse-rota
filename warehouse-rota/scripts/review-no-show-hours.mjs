// Fictional local fixtures verify the hours shown to a manager, without production writes.
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdtempSync, rmSync, mkdirSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { createRotaServer, monday, today, addDays } from '../server.mjs';

const require = createRequire(import.meta.url);
const { chromium } = require(process.env.CODEX_PRIMARY_RUNTIME_NODE_MODULES + '/playwright');
const directory = mkdtempSync(path.join(tmpdir(), 'rota-no-show-hours-'));
const app = createRotaServer({ dataDir: directory, password: 'no-show-review-password', seedExamples: false });
const week = monday(today()), loc = app.db.prepare('SELECT * FROM locations').get(), errors = [];
app.db.prepare('INSERT INTO locations (id,name,share_token,active) VALUES (?,?,?,1)').run('other-site', 'Other example site', 'other-example-token');
for (const [id, name] of [['avery', 'Avery Example'], ['bruno', 'Bruno Example']]) {
  app.db.prepare('INSERT INTO people (id,name,team,role,contract_minutes,location_id,active,row_order,default_department) VALUES (?,?,?,?,?,?,1,?,?)').run(id, name, 'Picking', 'Example colleague', 2400, loc.id, id === 'avery' ? 0 : 1, 'Picking');
}
const insert = (id, person, date, start, end, breaks, breakStart, kind = 'work', warehouse = 'Warehouse 1', locationId = loc.id) => {
  app.db.prepare('INSERT INTO shifts (id,person_id,location_id,date,start_time,end_time,break_minutes,break_start,kind,label,colour,note,department,warehouse) VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?)').run(id, person, locationId, date, start, end, breaks, breakStart, kind, 'Example shift', 'blue', '', 'Picking', warehouse);
};
insert('morning', 'avery', week, '08:00', '12:00', 0, null);
insert('training', 'avery', week, '13:00', '17:30', 30, '15:00', 'training', 'Warehouse 2');
insert('night', 'avery', addDays(week, 1), '22:00', '06:00', 30, '02:00');
insert('other-work', 'avery', week, '18:00', '22:00', 0, null, 'work', 'Warehouse 2', 'other-site');
insert('bruno-work', 'bruno', week, '08:00', '16:30', 30, '12:00');
insert('previous-night', 'bruno', addDays(week, -1), '22:00', '06:00', 30, '02:00');
app.db.prepare('INSERT INTO attendance (person_id,location_id,date,status,marked_at) VALUES (?,?,?,?,?)').run('avery', 'other-site', week, 'no_show', new Date().toISOString());
app.db.prepare('INSERT INTO attendance (person_id,location_id,date,status,marked_at) VALUES (?,?,?,?,?)').run('bruno', loc.id, addDays(week, -1), 'no_show', new Date().toISOString());
app.db.prepare('INSERT INTO day_plans VALUES (?,?,NULL,?)').run(loc.id, week, 960);
await new Promise(resolve => app.server.listen(0, '127.0.0.1', resolve));
const base = `http://127.0.0.1:${app.server.address().port}`;
const browser = await chromium.launch({ headless: true, executablePath: process.env.ROTA_REVIEW_CHROMIUM || '/workspace/scratch/13965183c3f3/browser-runtime/chromium', args: ['--no-sandbox', '--disable-dev-shm-usage'] });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 }, locale: 'en-GB' });
  page.on('pageerror', e => errors.push(e.message));
  await page.goto(base);
  await page.getByLabel('Manager password').fill('no-show-review-password');
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await page.locator('.colleague-row').first().waitFor();
  await page.locator('#location-picker').selectOption(loc.id);
  const saveLabel = async label => {
    await page.locator('[data-id="morning"]').click();
    assert.equal(await page.locator('#shift-label').isVisible(), true);
    assert.equal(await page.locator('#shift-kind option[value="b2b"]').count(), 0);
    if (label === 'B2B') await page.getByRole('button', { name: 'Use B2B label', exact: true }).click();
    else await page.locator('#shift-label').fill(label);
    assert.equal(await page.locator('#shift-kind').inputValue(), 'work');
    await page.locator('#modal').getByRole('button', { name: 'Save changes', exact: true }).click();
    await page.locator('#modal').waitFor({ state: 'hidden' });
    const saved = app.db.prepare("SELECT * FROM shifts WHERE id='morning'").get();
    assert.equal(saved.kind, 'work'); assert.equal(saved.start_time, '08:00'); assert.equal(saved.end_time, '12:00');
    assert.equal(saved.label, label || 'Shift');
  };
  await saveLabel('B2B');
  assert.equal(await page.locator('[data-id="morning"] .shift-tag').textContent(), 'B2B');
  assert.equal(await page.locator('[data-id="morning"] .shift-tag').evaluate(el => el.scrollWidth <= el.clientWidth + 1), true, 'B2B stays fully visible beside the time');
  await saveLabel('Priority');
  assert.equal(await page.locator('[data-id="morning"] .shift-tag').textContent(), 'Priority');
  await saveLabel('');
  assert.equal(await page.locator('[data-id="morning"] .shift-tag').count(), 0);
  await saveLabel('B2B');
  await page.locator('[data-id="training"]').click();
  await page.locator('#shift-label').fill('Gift wrap');
  await page.locator('#modal').getByRole('button', { name: 'Save changes', exact: true }).click();
  await page.locator('#modal').waitFor({ state: 'hidden' });
  assert.equal(app.db.prepare("SELECT kind FROM shifts WHERE id='training'").get().kind, 'training');
  assert.equal(await page.locator('[data-id="training"] .training-mark').textContent(), 'Training');
  assert.equal(await page.locator('[data-id="training"] .shift-tag').textContent(), 'Gift wrap');
  const hours = async locator => Number((await locator.textContent()).replace(/h|,/g, ''));
  const weeklyHours = person => hours(page.locator(`.colleague-row:has([data-drop-person="${person}"]) .hours-column strong`));
  const siteHours = () => hours(page.locator('.heading-summary > span').nth(1).locator('strong'));
  const dayHours = () => hours(page.locator('.day-stat').first().locator('strong'));
  const openDay = async () => {
    await page.locator('.view-toggle [data-action="view-day"]').click();
    await page.locator('.day-tab[data-day="0"]').click();
  };
  const mark = async status => {
    const row = page.locator('.day-person[data-person="avery"]');
    await row.locator(`[data-status="${status}"]`).click();
    if (status === 'unmarked') await row.locator('[data-status="unmarked"]').waitFor({ state: 'detached' });
    else await row.locator(`[data-status="${status}"][aria-pressed="true"]`).waitFor();
  };
  assert.equal(await weeklyHours('avery'), 15.5, 'A different location’s no show does not cancel attendance at this site');
  assert.equal(await weeklyHours('bruno'), 8, 'Previous-week overnight hours are not included in this week');
  assert.equal(await siteHours(), 23.5);
  await page.locator('[data-action="publish"]').click();
  await page.locator('#modal').getByRole('button', { name: 'Publish rota', exact: true }).click();
  await page.locator('#modal').waitFor({ state: 'hidden' });
  const snapshot = app.db.prepare('SELECT snapshot FROM publications WHERE location_id=?').get(loc.id).snapshot;
  await openDay();
  assert.equal(await dayHours(), 16);
  await mark('no_show');
  assert.equal(await dayHours(), 8, 'Both split work and training shifts are deducted after unpaid breaks');
  assert.equal(await siteHours(), 15.5);
  assert.match(await page.locator('.day-planning').textContent(), /8h short/);
  assert.equal(await page.locator('.day-tab[data-day="0"] small').textContent(), '1 on');
  assert.match(await page.locator('.attendance-summary').textContent(), /0 checked in · 1 no show · 1 unmarked/);
  await page.locator('#team-filter').selectOption('Picking');
  await page.locator('#warehouse-filter').selectOption('Warehouse 2');
  assert.equal(await dayHours(), 8, 'Required-hours comparisons include the whole site despite filters');
  await page.locator('#team-filter').selectOption('');
  await page.locator('#warehouse-filter').selectOption('');
  await page.locator('.view-toggle [data-action="view-week"]').click();
  assert.equal(await weeklyHours('avery'), 7.5);
  assert.equal(await page.locator('.day-column').first().locator('.day-summary').textContent(), '1 on · 8h');
  assert.equal(await page.locator('[data-drop-person="avery"][data-drop-date="' + week + '"] .weekly-no-show').count(), 2);
  await page.locator('.view-toggle [data-action="view-timeline"]').click();
  await page.locator('.day-tab[data-day="0"]').click();
  await page.locator('[data-action="coverage-full"]').click();
  assert.equal(await page.locator('.timeline-person').count(), 1, 'No shows provide no cover, including previous-week overnight carry-over');
  assert.equal(await page.locator('.timeline-person[data-id="bruno-work"]').count(), 1);
  assert.equal(await page.locator('.timeline-person[data-id="previous-night"]').count(), 0);
  await openDay();
  await mark('checked_in');
  assert.equal(await dayHours(), 16);
  assert.equal(await siteHours(), 23.5);
  await page.locator('.view-toggle [data-action="view-week"]').click();
  assert.equal(await weeklyHours('avery'), 15.5);
  await openDay();
  await mark('no_show');
  await mark('unmarked');
  assert.equal(await dayHours(), 16, 'Clearing attendance also restores the hours');
  await mark('no_show');
  await page.reload();
  await page.locator('.colleague-row').first().waitFor();
  assert.equal(await weeklyHours('avery'), 7.5, 'Deductions persist after reloading');
  assert.equal(await page.locator('[data-id="morning"] .shift-tag').textContent(), 'B2B');
  assert.equal(app.db.prepare('SELECT COUNT(*) AS n FROM shifts').get().n, 6);
  assert.equal(app.db.prepare('SELECT snapshot FROM publications WHERE location_id=?').get(loc.id).snapshot, snapshot);
  const shared = await (await page.request.get(base + `/api/public/${loc.share_token}?week=${week}`)).json();
  assert.equal(shared.shifts.length, 4);
  assert.equal(shared.attendance, undefined);
  assert.equal(shared.previousAttendance, undefined);
  const publicPage = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
  await publicPage.goto(base + '/rota/' + loc.share_token + '?week=' + week);
  await publicPage.locator('.colleague-row').first().waitFor();
  assert.equal(await hours(publicPage.locator('.colleague-row').first().locator('.hours-column strong')), 15.5, 'Published totals keep the planned rota and attendance remains private');
  assert.equal(await publicPage.locator('.shift-tag').getByText('B2B', { exact: true }).count(), 1);
  assert.equal(await publicPage.locator('.shift-tag').getByText('Gift wrap', { exact: true }).count(), 1);
  const preview = path.resolve('review');
  mkdirSync(preview, { recursive: true });
  await publicPage.screenshot({ path: path.join(preview, 'warehouse-rota-shift-labels-preview.png'), fullPage: true });
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ b2bLabel: true, manualLabels: true, clearLabel: true, labelsKeepShiftTypesAndTimes: true, sharedLabels: true, splitWorkAndTraining: true, unpaidBreaks: true, dailyAndWeeklyDeduction: true, requirementsUpdated: true, correctionAndClearRestoreHours: true, reloadPersistence: true, crossLocationAttendance: true, previousNightCover: true, shiftsAndPublicationPreserved: true, browserErrors: 0 }));
} finally {
  await browser.close();
  await app.close();
  rmSync(directory, { recursive: true, force: true });
}
